    #[test]
    #[ignore = "daily"]
    fn setup_refreshes_only_workflow_files_and_keeps_foreign_release() {
        let repo = Repo::new();
        repo.put("mods/example/sunrise-mod.toml", MOD);
        let foreign = ".github/workflows/release.yml";
        repo.put(foreign, "name: custom");
        repo.put(".gitignore", "/target\n");
        let obsolete = [
            ".github/workflows/rebuild.yml",
            ".github/workflows/sunrise-release-jobs.yml",
            ".github/actions/sunrise-release-tool/action.yml",
            "sunrise_release.py",
            "mods/example/sunrise_release_github.py",
        ];
        for path in obsolete {
            repo.put(path, "old");
        }
        repo.commit();
        repo.git(["remote", "remove", "origin"]);
        let head = repo.git(["rev-parse", "HEAD"]);
        repo.release("mods/example", &["setup"], refused_check)
            .unwrap();
        assert_eq!(repo.git(["rev-parse", "HEAD"]), head);
        assert!(repo.git(["tag", "--list"]).is_empty());
        assert_eq!(
            fs::read_to_string(repo.root.join(foreign)).unwrap(),
            "name: custom"
        );
        assert_eq!(
            fs::read_to_string(repo.root.join(".gitignore")).unwrap(),
            "/target\n"
        );
        for path in obsolete {
            assert!(!repo.root.join(path).exists(), "{path}");
        }
        assert!(
            fs::read_to_string(
                repo.root
                    .join(".github/workflows/sunrise-release-example.yml")
            )
            .unwrap()
            .ends_with("path: mods/example\n")
        );
        repo.put(foreign, "uses: ./.github/actions/sunrise-release-tool");
        repo.release("mods/example", &["setup"], refused_check)
            .unwrap();
        assert!(!repo.root.join(foreign).exists());
    }

    #[test]
    #[ignore = "daily"]
    fn refuses_dirty_branch_local_or_remote_tag_and_behind_branch() {
        let repo = Repo::new();
        repo.put(MANIFEST, MOD);
        repo.commit();
        let head = repo.git(["rev-parse", "HEAD"]);
        repo.put("dirty", "untracked");
        assert!(
            repo.release(".", &["patch"], refused_check)
                .unwrap_err()
                .contains("uncommitted changes")
        );
        fs::remove_file(repo.root.join("dirty")).unwrap();
        repo.git(["tag", "v1.4.3"]);
        assert!(
            repo.release(".", &["patch"], refused_check)
                .unwrap_err()
                .contains("already exists")
        );
        repo.git(["push", "-u", "origin", "main", "refs/tags/v1.4.3"]);
        repo.git(["tag", "-d", "v1.4.3"]);
        assert!(
            repo.release(".", &["patch"], refused_check)
                .unwrap_err()
                .contains("already exists")
        );
        repo.put("next", "additional commit");
        repo.commit();
        repo.git(["push", "origin", "main"]);
        repo.git(["reset", "--hard", &head]);
        assert!(
            repo.release(".", &["minor"], refused_check)
                .unwrap_err()
                .contains("not up to date")
        );
        assert!(!repo.root.join(CALLER).exists());
    }

    #[test]
    #[ignore = "daily"]
    fn preview_and_failed_check_leave_files_and_refs_untouched() {
        let repo = Repo::new();
        repo.put(MANIFEST, MOD);
        repo.commit();
        let head = repo.git(["rev-parse", "HEAD"]);
        let check = |package: &Path, tag: &str| {
            assert_ne!(package, repo.root);
            assert_eq!(tag, "v1.4.3");
            assert_eq!(read_manifest(package).unwrap().version.to_string(), "1.4.3");
            fs::write(package.join("compile-output"), "only in scratch").unwrap();
            Ok(())
        };
        repo.release(".", &["--check"], check).unwrap();
        assert_eq!(
            repo.release(".", &["patch"], |p, t| {
                check(p, t)?;
                Err("page check failed".into())
            })
            .unwrap_err(),
            "page check failed"
        );
        assert_eq!(fs::read_to_string(repo.root.join(MANIFEST)).unwrap(), MOD);
        assert!(!repo.root.join("compile-output").exists());
        assert!(!repo.root.join(CALLER).exists());
        assert!(repo.git(["status", "--porcelain"]).is_empty());
        assert!(repo.git(["tag", "--list"]).is_empty());
        assert_eq!(repo.git(["rev-parse", "HEAD"]), head);
        assert!(repo.git.text(&repo.bare, ["show-ref"]).is_err());
    }

    #[test]
    #[ignore = "daily"]
    fn publishes_native_package_and_keeps_pinned_dependencies() {
        let repo = Repo::new();
        repo.put("mods/example/sunrise-mod.toml", &format!("{MOD}{NATIVE}"));
        repo.put("mods/example/Cargo.toml", CARGO);
        repo.put("mods/example/Cargo.lock", LOCK);
        repo.put(
            ".github/workflows/release.yml",
            "run: python sunrise_release.py",
        );
        repo.commit();
        repo.git(["push", "-u", "origin", "main"]);
        repo.release("mods/example", &["minor"], |package, tag| {
            assert_eq!(tag, "example/v1.5.0");
            assert_eq!(read_manifest(package).unwrap().version.to_string(), "1.5.0");
            Ok(())
        })
        .unwrap();
        assert_eq!(
            fs::read_to_string(repo.root.join("mods/example/Cargo.toml")).unwrap(),
            CARGO.replace("1.4.2", "1.5.0")
        );
        assert_eq!(
            fs::read_to_string(repo.root.join("mods/example/Cargo.lock")).unwrap(),
            LOCK.replace("1.4.2", "1.5.0")
        );
        assert_eq!(
            fs::read_to_string(repo.root.join("mods/example/sunrise-mod.toml")).unwrap(),
            format!("{}{NATIVE}", MOD.replace("1.4.2", "1.5.0"))
        );
        assert_eq!(repo.git(["log", "-1", "--format=%s"]), "Release 1.5.0");
        assert_eq!(
            repo.git(["show", "--pretty=format:", "--name-only", "HEAD"]),
            ".github/workflows/release.yml\n.github/workflows/sunrise-release-example.yml\nmods/example/Cargo.lock\nmods/example/Cargo.toml\nmods/example/sunrise-mod.toml"
        );
        let head = repo.git(["rev-parse", "HEAD"]);
        for reference in ["refs/heads/main", "refs/tags/example/v1.5.0"] {
            assert_eq!(
                repo.git.text(&repo.bare, ["rev-parse", reference]).unwrap(),
                head
            );
        }
        assert!(repo.git(["status", "--porcelain"]).is_empty());
    }
